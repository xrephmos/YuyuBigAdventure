/** 进入第 n 关时已经拥有的武器：初始武器 + 之前各关的通关奖励与宝箱。 */
export function weaponsForLevel(index, starting) {
  const list = [...starting];
  for (let i = 0; i < index; i += 1) for (const id of [LEVELS[i].reward, LEVELS[i].chest]) if (id && !list.includes(id)) list.push(id);
  return list;
}

/** 第 n 关可用的技能及其次数：之前各关与本关学会的技能，每章开始时次数恢复。 */
export function skillsForLevel(index, skills) {
  const result = {};
  for (let i = 0; i <= index; i += 1) {
    const id = LEVELS[i].skill;
    if (id) result[id] = skills[id].charges;
  }
  return result;
}
