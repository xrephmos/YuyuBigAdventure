/**
 * 怪物的心阵按章节分档成长：前期刚好够连上几下，越往后越厚，
 * 由更多的武器、技能和强化来应付。ranks 里没写的档位沿用最近的较低档。
 *
 * 每一档可以写一套心阵（字符画），也可以写几套变体（字符画的数组），遭遇时随机取一套，玩家没法背答案。
 * 普通怪物的心阵是它自己的“符号”（兵像棋子、城堡有城垛、王后戴王冠），左右对称或中心对称；
 * 同一档的变体共用一个符号模板，只在少数格子上成组增减。
 * 心阵的主体由上下左右相邻的心连成一片（连击只认上下左右相邻），斜向只做轮廓的边。
 * 变体都由 tools/gen-matrices.mjs 按模板穷举，并用和单元测试相同的形状检查与连击求解器筛过。
 */
export function variantsAt(def, rank = 0) {
  const defined = Object.keys(def.ranks).map(Number).sort((a, b) => a - b);
  const lower = defined.filter((k) => k <= rank);
  const pick = lower.length ? lower[lower.length - 1] : defined[0];
  return def.rankValues[pick];
}

/** 某一档的第 variant 套心阵（默认第一套）。 */
export const heartsAt = (def, rank = 0, variant = 0) => {
  const list = variantsAt(def, rank);
  return list[variant % list.length];
};

/** 一档里写的是一套还是几套：统一成“几套”的数组。 */
const asVariants = (entry) => (typeof entry[0] === "string" ? [entry] : entry);

for (const monster of Object.values(MONSTERS)) {
  monster.rankValues = Object.fromEntries(Object.entries(monster.ranks).map(([k, entry]) => [k, asVariants(entry).map(parseMatrix)]));
  monster.matrix = asVariants(Object.values(monster.ranks)[0])[0];
  monster.matrixValues = heartsAt(monster, 0);
  monster.armored = Object.values(monster.ranks).some((entry) => asVariants(entry).some((art) => art.some((row) => row.includes("A"))));
  if (monster.rebirth) monster.rebirth.matrixValues = parseMatrix(monster.rebirth.matrix);
}

